"""
AI-driven audit-trail intelligence (P4.5, the tender).

Turns one already-flagged app/security_analytics.py `SecurityAlert` (a
deterministic heuristic finding -- see that module for the rules themselves
and why they carry no manual configuration) into a short prose explanation
via the local LLM (ai/local_llm.py): why the pattern is worth a look and one
concrete next step. Same "never raise, degrade gracefully" contract as
cds_hint.py/report_narrative.py: no Ollama -> `explanation` comes back None,
the alert's own structured fields (rule/severity/detail/counts) are still
there on their own.

Not a second source of truth: the LLM only sees the alert's own fields
(role/facility/rule/window/counts -- shapes, not clinical values, same M8
discipline the alert row itself already follows) and is told not to invent
anything beyond them. It never decides whether something IS an anomaly --
security_analytics.py's deterministic rules already did that; this only
adds prioritisation language for the reviewing admin, same "reference aid,
not an autonomous decision" framing as every other AI feature here.
"""
from __future__ import annotations

from typing import Any

from .local_llm import generate_text

DISCLAIMER = (
    "Explanation generated by a local, uncertified language model from the "
    "alert's own fields -- a reading aid for prioritisation, not a verdict. "
    "The underlying finding is a deterministic rule, not the LLM's judgement."
)

_RULE_CONTEXT = {
    "distinct_patient_fanout": (
        "an actor accessing an unusually large number of distinct patient "
        "records within a single hour -- a shape associated with bulk "
        "browsing or data exfiltration rather than routine one-patient-at-a-"
        "time clinical care"
    ),
    "off_hours_access": (
        "an actor accessing patient records during Malaysia's quiet hours "
        "(00:00-05:00 MYT) -- not necessarily malicious for an "
        "emergency-capable clinic, but worth correlating with whether that "
        "actor is rostered for an overnight shift"
    ),
}


def generate_alert_explanation(alert: dict[str, Any]) -> dict:
    """`alert` carries the same fields as schemas.SecurityAlertOut (pass
    `SecurityAlertOut.model_validate(row).model_dump()` from the router)."""
    rule_context = _RULE_CONTEXT.get(
        alert["rule"], "an access pattern flagged by a deterministic rule",
    )

    prompt = (
        "You are helping a hospital security admin triage ONE flagged audit "
        f"alert. Context for this kind of rule: {rule_context}.\n\n"
        "Write 2-3 short sentences: why this specific alert is worth a look, "
        "and one concrete next step to verify it (e.g. what to check, who to "
        "ask). Use ONLY the fields below -- never invent a patient name, "
        "diagnosis, or any detail not given here.\n\n"
        f"Rule: {alert['rule']}\n"
        f"Severity: {alert['severity']}\n"
        f"Actor role: {alert.get('actor_role') or 'unknown'}\n"
        f"Actor facility: {alert.get('actor_facility') or 'unknown'}\n"
        f"Window: {alert['window_start']} to {alert['window_end']}\n"
        f"Times seen: {alert['times_seen']}\n"
        f"Detail: {alert['detail']}\n"
    )

    return {
        "explanation": generate_text(prompt, max_tokens=200),
        "disclaimer": DISCLAIMER,
    }
