"""
Clinical Decision Support hint (P4.3b, the tender).

A clinician-facing REFERENCE AID -- never an autonomous diagnosis or
prescription decision (every open-weight local model's acceptable-use terms
forbid autonomous clinical decision-making anyway; see
healthcare/On-Prem Clinical AI.md). Given the patient's known
conditions/allergies/active medications plus whatever the clinician has
typed into the SOAP note so far, this asks the local LLM (ai/local_llm.py)
for a short "things to consider" note, and separately flags any active
medication whose name plainly overlaps a recorded allergy substance --
deterministic, not the LLM. Medication-safety/allergy screening is a
rule-engine job, not a generative one (see the vault's On-Prem Clinical AI
stack table); a real drug-class-aware check needs the licensed drug DB
integration tracked at P4.4 -- this is a cheap, honest floor, not that.

Same "never raise, degrade gracefully" discipline as ai/summarize.py: if
Ollama is unavailable, `hint` comes back None and the caller shows the
allergy-conflict check alone (that part needs no LLM).
"""
from __future__ import annotations

from typing import Optional

from .local_llm import generate_text

DISCLAIMER = (
    "Reference aid only, generated by a local, uncertified language model -- "
    "not a diagnosis, not a prescription decision. Always apply independent "
    "clinical judgement."
)


def _allergy_conflicts(allergies: list[dict], active_medications: list[dict]) -> list[str]:
    """Plain, case-insensitive substring match between a recorded allergy
    substance and an active medication's drug name -- catches the obvious
    case (a 'Penicillin' allergy against a 'Penicillin'-containing
    prescription). NOT a drug-class/cross-reactivity engine."""
    conflicts = []
    for allergy in allergies:
        substance = (allergy.get("substance") or "").strip().lower()
        if not substance:
            continue
        for med in active_medications:
            drug_name = (med.get("drug_name") or "").strip().lower()
            if drug_name and (substance in drug_name or drug_name in substance):
                conflicts.append(
                    f"Active medication '{med['drug_name']}' may relate to recorded "
                    f"allergy '{allergy['substance']}' ({allergy.get('severity', 'unknown')} severity)."
                )
    return conflicts


def generate_cds_hint(patient: dict, draft_note: dict, reason: Optional[str]) -> dict:
    """`patient` is the same shape ai/summarize.py's handover brief takes
    (routers/patients.py::_serialize_patient's output). `draft_note` carries
    whatever SOAP text the clinician has typed so far -- any field may be
    empty; nothing is persisted before sign-off, this never writes anything."""
    active_conditions = [c["name"] for c in patient.get("conditions", []) if c.get("status") == "active"]
    chronic = [c["name"] for c in patient.get("conditions", []) if c.get("is_chronic")]
    allergies = patient.get("allergies", [])
    active_meds = [m for m in patient.get("medications", []) if m.get("active")]

    prompt = (
        "You are a clinical decision support assistant giving a REFERENCE "
        "note to a clinician mid-consultation -- not a diagnosis. Given this "
        "context, write 2-4 short bullet points: things worth considering "
        "(possible differentials, relevant history, contraindication flags) "
        "using ONLY the data below. Do not invent findings not present here. "
        "Plain clinical language, no preamble.\n\n"
        f"Reason for visit: {reason or 'not given'}\n"
        f"Active conditions: {', '.join(active_conditions) or 'none recorded'}\n"
        f"Chronic conditions: {', '.join(chronic) or 'none recorded'}\n"
        f"Known allergies: {', '.join(a['substance'] for a in allergies) or 'none recorded'}\n"
        f"Active medications: {', '.join(m['drug_name'] for m in active_meds) or 'none recorded'}\n"
        f"Subjective (typed so far): {draft_note.get('subjective') or '(not yet entered)'}\n"
        f"Objective (typed so far): {draft_note.get('objective') or '(not yet entered)'}\n"
    )

    return {
        "hint": generate_text(prompt, max_tokens=300),
        "allergy_conflicts": _allergy_conflicts(allergies, active_meds),
        "disclaimer": DISCLAIMER,
    }
