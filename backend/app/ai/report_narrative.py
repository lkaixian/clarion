"""
NL report narrative (P4.3c, the tender).

Turns the Reporting engine's already-structured output
(app/reporting_engine.py's run_report result -- columns + rows, already
facility-scoped, already anonymized if the caller asked for it) into a short
prose summary via the local LLM (ai/local_llm.py). Same "never raise,
degrade gracefully" contract as cds_hint.py/summarize.py: no Ollama ->
narrative comes back None, caller still has the table.

Not a second source of truth: the LLM only sees the numbers the engine
already computed (or a capped row sample) and is told not to invent any --
a report narrative that hallucinates a figure nobody in the table typed is
worse than no narrative.
"""
from __future__ import annotations

from typing import Any

from .local_llm import generate_text

DISCLAIMER = (
    "Narrative generated by a local, uncertified language model from the table "
    "above -- a reading aid, not a substitute for reviewing the data itself."
)

_MAX_NARRATIVE_ROWS = 30


def _rows_to_text(columns: list[dict], rows: list[list[Any]]) -> str:
    headers = [c["label"] for c in columns]
    lines = [" | ".join(headers)]
    for row in rows[:_MAX_NARRATIVE_ROWS]:
        lines.append(" | ".join("" if v is None else str(v) for v in row))
    return "\n".join(lines)


def generate_report_narrative(dataset_label: str, result: dict) -> dict:
    """`result` is exactly app/reporting_engine.run_report's return value."""
    columns, rows, row_count = result["columns"], result["rows"], result["row_count"]
    if not rows:
        return {"narrative": None, "disclaimer": DISCLAIMER}

    shown = min(len(rows), _MAX_NARRATIVE_ROWS)
    omitted_note = f" (showing the first {shown} of {row_count} rows)" if row_count > shown else ""

    prompt = (
        "You are summarising an operational report table for a clinic manager. "
        "Write a short prose narrative (3-5 sentences): the notable pattern, "
        "any standout value, one operational takeaway. Use ONLY the numbers in "
        "the table below -- never invent a figure that isn't there. Plain "
        "language, no preamble, no markdown.\n\n"
        f"Report: {dataset_label}{omitted_note}\n\n"
        f"{_rows_to_text(columns, rows)}\n"
    )

    return {
        "narrative": generate_text(prompt, max_tokens=250),
        "disclaimer": DISCLAIMER,
    }
