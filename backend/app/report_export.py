"""P3.6: PDF / Excel rendering for a reporting_engine.run_report() result
("export PDF and Excel"). Pure presentation over the already-
computed `{columns, rows}` shape -- no query logic here.

PDF uses reportlab's `platypus` Table/SimpleDocTemplate rather than the raw
Canvas app/document_generation.py uses -- that file's docstring explains why
raw Canvas suits a fixed-layout one-page form; a report is an arbitrary-
length table, which is exactly what platypus's Table/SimpleDocTemplate (already
in the same reportlab dependency) is for -- no new dependency either way.
"""
from __future__ import annotations

import io
import re
from datetime import datetime, timezone
from typing import Any, Dict, List

import openpyxl
from openpyxl.styles import Font
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas as _canvas
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .appointments import MALAYSIA_TZ


def _fmt_dt(value) -> str:
    """DD-MM-YYYY HH:MM, 24-hour, Malaysia time. Takes a datetime or an ISO
    string; a naive value is UTC (the DB convention, TZDateTime round-trips naive)."""
    if value is None:
        return "-"
    if isinstance(value, str):
        value = datetime.fromisoformat(value)
    if value.tzinfo is None:
        value = value.replace(tzinfo=timezone.utc)
    return value.astimezone(MALAYSIA_TZ).strftime("%d-%m-%Y %H:%M")


def render_pdf(title: str, result: Dict[str, Any], generated_by: str, generated_at: str) -> bytes:
    columns: List[dict] = result["columns"]
    rows: List[list] = result["rows"]

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=landscape(A4),
        leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
    )
    styles = getSampleStyleSheet()
    story = [
        Paragraph(title, styles["Title"]),
        Paragraph(f"Generated by {generated_by} at {_fmt_dt(generated_at)} &middot; {result['row_count']} row(s)", styles["Normal"]),
        Spacer(1, 8 * mm),
    ]

    header = [c["label"] for c in columns]
    body = [["" if v is None else str(v) for v in row] for row in rows]
    table = Table([header] + body, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a8a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(table)
    if result.get("truncated"):
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph("Row cap reached -- narrow the filters for a complete export.", styles["Normal"]))
    doc.build(story)
    return buf.getvalue()


def render_excel(title: str, result: Dict[str, Any]) -> bytes:
    columns: List[dict] = result["columns"]
    rows: List[list] = result["rows"]

    wb = openpyxl.Workbook()
    ws = wb.active
    # Excel forbids \ / ? * [ ] : in sheet names, bars a leading/trailing
    # apostrophe, and caps the length at 31 (dataset labels like "A / B" 500'd).
    ws.title = re.sub(r"[\\/?*\[\]:\x00-\x1f]", "-", title).strip("' ")[:31] or "Report"

    header_font = Font(bold=True, color="FFFFFF")
    for col_idx, c in enumerate(columns, start=1):
        cell = ws.cell(row=1, column=col_idx, value=c["label"])
        cell.font = header_font
        cell.fill = openpyxl.styles.PatternFill("solid", fgColor="1E3A8A")
    for row_idx, row in enumerate(rows, start=2):
        for col_idx, v in enumerate(row, start=1):
            ws.cell(row=row_idx, column=col_idx, value=v)
    for col_idx in range(1, len(columns) + 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(col_idx)].width = 20

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def render_notifiable_disease_pdf(report, patient) -> bytes:
    """P3.7: a single-page notification form in the shape
    MOH's e-Notifikasi portal (enotifikasi.moh.gov.my) asks for. There is
    no public submission API (see healthcare/National Interoperability.md
    -- same situation as MHNexus/FHIR) so this PDF is the artifact a human
    re-keys from when filing there -- same "simplest tool that draws a
    form" choice as app/document_generation.py's raw Canvas use, reused
    directly here rather than routing a one-off form through the
    table-shaped render_pdf above."""
    buf = io.BytesIO()
    c = _canvas.Canvas(buf, pagesize=A4)
    _, page_h = A4
    x = 20 * mm
    y = [page_h - 20 * mm]  # boxed so the nested closure can mutate it

    def line(text: str, size: int = 11, bold: bool = False, gap: float = 7 * mm) -> None:
        c.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        c.drawString(x, y[0], text)
        y[0] -= gap

    line("NOTIFIABLE DISEASE REPORT", 16, bold=True, gap=9 * mm)
    line("Prevention & Control of Infectious Diseases Act 1988 (Act 342)", 9)
    line("For submission at enotifikasi.moh.gov.my", 9, gap=10 * mm)

    line(f"Patient: {patient.full_name}", bold=True)
    line(f"NRIC / ID: {patient.national_id or '-'}")
    line(f"Date of birth: {patient.date_of_birth}")
    line(f"Gender: {patient.gender or '-'}", gap=10 * mm)

    line(f"Disease: {report.disease_name}", bold=True)
    line(f"Onset date: {report.onset_date or '-'}")
    if report.notes:
        line(f"Notes: {report.notes}", gap=10 * mm)
    else:
        y[0] -= 3 * mm

    line(f"Reporting facility: {report.facility_name}")
    line(f"Reported by: {report.reported_by_name or '-'} at {_fmt_dt(report.reported_at)}")
    if report.submitted_at:
        line(f"Marked submitted at: {_fmt_dt(report.submitted_at)}")

    c.showPage()
    c.save()
    return buf.getvalue()
