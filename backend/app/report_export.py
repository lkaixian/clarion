"""P3.6: PDF / Excel rendering for a reporting_engine.run_report() result
("export PDF and Excel"). Pure presentation over the already-
computed `{columns, rows}` shape -- no query logic here.

PDF uses reportlab's `platypus` Table/SimpleDocTemplate rather than the raw
Canvas app/document_generation.py uses -- that file's docstring explains why
raw Canvas suits a fixed-layout one-page form; a report is an arbitrary-
length table, which is exactly what platypus's Table/SimpleDocTemplate (already
in the same reportlab dependency) is for -- no new dependency either way.
"""
from __future__ import annotations

import io
from typing import Any, Dict, List

import openpyxl
from openpyxl.styles import Font
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def render_pdf(title: str, result: Dict[str, Any], generated_by: str, generated_at: str) -> bytes:
    columns: List[dict] = result["columns"]
    rows: List[list] = result["rows"]

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=landscape(A4),
        leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
    )
    styles = getSampleStyleSheet()
    story = [
        Paragraph(title, styles["Title"]),
        Paragraph(f"Generated by {generated_by} at {generated_at} &middot; {result['row_count']} row(s)", styles["Normal"]),
        Spacer(1, 8 * mm),
    ]

    header = [c["label"] for c in columns]
    body = [["" if v is None else str(v) for v in row] for row in rows]
    table = Table([header] + body, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a8a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(table)
    if result.get("truncated"):
        story.append(Spacer(1, 4 * mm))
        story.append(Paragraph("Row cap reached -- narrow the filters for a complete export.", styles["Normal"]))
    doc.build(story)
    return buf.getvalue()


def render_excel(title: str, result: Dict[str, Any]) -> bytes:
    columns: List[dict] = result["columns"]
    rows: List[list] = result["rows"]

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = title[:31] or "Report"  # Excel sheet-name length limit

    header_font = Font(bold=True, color="FFFFFF")
    for col_idx, c in enumerate(columns, start=1):
        cell = ws.cell(row=1, column=col_idx, value=c["label"])
        cell.font = header_font
        cell.fill = openpyxl.styles.PatternFill("solid", fgColor="1E3A8A")
    for row_idx, row in enumerate(rows, start=2):
        for col_idx, v in enumerate(row, start=1):
            ws.cell(row=row_idx, column=col_idx, value=v)
    for col_idx in range(1, len(columns) + 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(col_idx)].width = 20

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
