#!/usr/bin/env python3
"""build_failures.py - FAILURES.md: only fail + xfail rows of the Clean Prod Pi, each with a plain-language reason.
Run after build_matrix.py (reads matrix.json).  stdlib only."""
import json, os, re

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
REPORT = os.path.join(ROOT, "report")
STRESS = os.path.abspath(os.path.join(ROOT, "..", "..", "..", "stress"))
REC = json.load(open(os.path.join(REPORT, "matrix.json"), encoding="utf-8"))["records"]

# (id, text that must appear in the test name) -> reason. First match wins; the raw detail is always shown too.
WHY = [
    ("A6", "False-", "false positive: the site returns its index.html (200) for unknown paths and the check mistakes that for a leaked file"),
    ("A1", "inventory", "POST /payments/webhook/{provider} is unauthenticated by design (the gateway signs it with HMAC)"),
    ("A1", "", "public emergency endpoints validate input (422) before checking login; by design for an emergency-first system"),
    ("A5", "x\\x00", "harness error: the HTTP client refuses to send a NUL byte, so the server was never tested"),
    ("A3", "", "a spoofed X-Forwarded-For header got past the per-IP login limiter (behind Cloudflare the real client IP may be hidden)"),
    ("A9", "", "fail2ban is not installed"),
    ("A10", "passwordauth", "SSH allows password login"),
    ("A10", "permitroot", "SSH root login is allowed with a key (without-password)"),
    ("A11", "", "dependency / image scan reports vulnerabilities (see sec/pip-audit.txt, npm-audit.txt, trivy)"),
    ("A12", "", "containers still hold default secrets (MARIADB_METRICS_PASSWORD, MINIO_SECRET_KEY are change-me values)"),
    ("CK1", "host_prefix", "no __Host- cookie prefix (it needs Path=/ and no Domain, which conflicts with narrowing the Path)"),
    ("CK1", "", "refresh cookie has Path=/, so the browser sends it to every route, not just /auth"),
    ("CK2", "", "plain http:// returns 200 instead of redirecting: Cloudflare 'Always Use HTTPS' is off"),
    ("CK3", "", "the capture of the Pi's network interface contained the demo password in plaintext (likely the plain-http login; capture not yet inspected)"),
    ("CK4", "", "the Caddy-to-backend hop is plaintext by design on an isolated network; documented residual risk"),
    ("CK7", "", "after a refresh token is reused the token family is not revoked: the legitimate successor token still works"),
    ("CK8", "", "the endpoint honours the cookie on a request with a foreign Origin; defence relies on SameSite=Strict only"),
    ("CK11", "", "login response has no Cache-Control: no-store"),
    ("T2", "", "HSTS max-age is 300 s; accepted only because APP_ENV=demo"),
    ("T4", "", "published Docker ports bypass the host firewall: the DOCKER-USER chain has no DROP rule"),
    ("T5", "", "an internal service is reachable from any container on the shared Docker network (no edge/internal split), or Redis has no password"),
    ("N1", "", "99.76 % of requests succeeded under network shaping (needs 99.9 %)"),
    ("N7", "", "the tunnel took 22.8 s to recover (limit 5 s)"),
    ("H4", "", "swap churn 348 pages/s under memory pressure (limit 100); request latency itself held"),
    ("H8", "", "p95 252.8 ms under the 1 GB disk load: 2.8 ms over the 250 ms limit"),
    ("RN1", "", "known gap: no generic Idempotency-Key header, so a retried POST /patients creates a duplicate"),
    ("RN2", "", "known gap: a lost refresh response cannot be recovered by replaying the rotated token (it returns 401)"),
    ("RN7", "", "known gap: webhook events carry no timestamp, so an old signed event cannot be rejected"),
    ("RN8", "", "setup problem: Toxiproxy refused connections, so the stalled-client test did not run properly"),
    ("RN9", "", "only 23 of 100 requests succeeded after a blackout; the retry storm gave up on 77"),
]


def why(r):
    for i, key, txt in WHY:
        if r["id"] == i and key in r["test"]:
            return txt
    return r["note"]


def cell(x, n=160):
    return str(x).replace("\n", " ").replace("|", "/")[:n]


bad = [r for r in REC if r["env"] == "clean" and r["status"] in ("fail", "xfail")]
order = {g: k for k, g in enumerate(["N", "H", "D", "R", "RN", "CK", "T", "A"])}
bad.sort(key=lambda r: (order.get(r["group"], 9), int(re.search(r"\d+", r["id"]).group()), r["test"]))
nf, nx = sum(r["status"] == "fail" for r in bad), sum(r["status"] == "xfail" for r in bad)
out = ["# Failures and known gaps: Clean Prod Pi (192.168.1.7)\n",
       f"Generated by `build_failures.py` from `matrix.json`. **{nf} failed, {nx} known gaps (xfail).** Only those two statuses are listed; "
       "void runs (tests that never ran) and passes are in `STATUS.md` / `matrix.csv`. A parametrized test is one row per case.\n",
       "| Status | ID | Test | Why | Raw detail | Evidence |", "|---|---|---|---|---|---|"]
for r in bad:
    out.append(f"| {r['status']} | {r['id']} | {cell(r['test'], 70)} | {cell(why(r))} | {cell(r['detail'])} | `{r['src']}` |")
open(os.path.join(REPORT, "FAILURES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"FAILURES.md: {nf} fail, {nx} xfail")

# ---- SVG version: ../stress/failures-clean.svg (same palette as the coverage SVGs)
import textwrap
from xml.sax.saxutils import escape as esc
BG, FG, GREY, LINE = "#0d1117", "#e6edf3", "#8b949e", "#30363d"
COL = {"fail": "#da3633", "xfail": "#58a6ff"}
W, X = 1500, (24, 100, 160, 520)          # status chip, id, test, why
LH, PAD = 15, 9
rows, y = [], 92
for r in bad:
    why_l = textwrap.wrap(why(r), 100) or [""]
    det = cell(r["detail"], 150)
    test_l = textwrap.wrap(cell(r["test"], 120), 52)[:3]
    n = max(len(why_l) + (1 if det else 0), len(test_l))
    h = n * LH + 2 * PAD
    p = [f'<line x1="16" x2="{W-16}" y1="{y}" y2="{y}" stroke="{LINE}"/>',
         f'<rect x="{X[0]}" y="{y+PAD-2}" width="62" height="17" rx="8" fill="{COL[r["status"]]}"/>',
         f'<text x="{X[0]+31}" y="{y+PAD+11}" text-anchor="middle" font-size="11" font-weight="700" fill="#fff">{r["status"]}</text>',
         f'<text x="{X[1]}" y="{y+PAD+11}" font-size="12" font-weight="700" fill="{FG}">{esc(r["id"])}</text>']
    for k, l in enumerate(test_l):
        p.append(f'<text x="{X[2]}" y="{y+PAD+11+k*LH}" font-size="11" fill="{GREY}">{esc(l)}</text>')
    for k, l in enumerate(why_l):
        p.append(f'<text x="{X[3]}" y="{y+PAD+11+k*LH}" font-size="12" fill="{FG}">{esc(l)}</text>')
    if det:
        p.append(f'<text x="{X[3]}" y="{y+PAD+11+len(why_l)*LH}" font-size="10" fill="{GREY}">{esc(det)}</text>')
    rows.append("".join(p)); y += h
H = y + 30
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" font-family="Segoe UI,Helvetica,Arial,sans-serif">',
       f'<rect width="{W}" height="{H}" fill="{BG}"/>',
       f'<text x="24" y="34" font-size="20" font-weight="700" fill="{FG}">Failures and known gaps: Clean Prod Pi (192.168.1.7)</text>',
       f'<text x="24" y="56" font-size="12" fill="{GREY}">{nf} failed (red), {nx} known gaps (blue). Void runs and passes are not listed. Source: qa/result/FAILURES.md</text>',
       f'<text x="{X[0]}" y="80" font-size="11" fill="{GREY}">STATUS</text><text x="{X[1]}" y="80" font-size="11" fill="{GREY}">ID</text>'
       f'<text x="{X[2]}" y="80" font-size="11" fill="{GREY}">TEST</text><text x="{X[3]}" y="80" font-size="11" fill="{GREY}">WHY (grey line: raw detail)</text>',
       *rows, "</svg>"]
open(os.path.join(STRESS, "failures-clean.svg"), "w", encoding="utf-8").write("\n".join(svg))
print("failures-clean.svg", W, "x", H)
